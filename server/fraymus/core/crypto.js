import { FNV_OFFSET, FNV_PRIME } from './constants.js';

// ── Hex conversion ──
export function hex(u8) {
  return Array.from(u8, (b) => b.toString(16).padStart(2, '0')).join('');
}

export function unhex(h) {
  return new Uint8Array((h.match(/../g) || []).map((x) => parseInt(x, 16)));
}

export function toHex(bytes) {
  return Array.from(bytes, (b) => b.toString(16).toUpperCase().padStart(2, '0')).join(' ');
}

// ── SHA-256: async (Web Crypto, hardware-accelerated) ──
export async function sha256(data) {
  const buf = data instanceof ArrayBuffer ? data : data.buffer
    ? data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength)
    : new TextEncoder().encode(data);
  return new Uint8Array(await crypto.subtle.digest('SHA-256', buf));
}

export async function sha256hex(data) {
  return hex(await sha256(data));
}

